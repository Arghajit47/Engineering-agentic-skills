#!/usr/bin/env python3
"""Regenerate the `## Reference files` block in every SKILL.md.

A reference file no SKILL.md points at is invisible to the agent that needs it —
39 of 113 had drifted that way. This makes the index generated, so a reference
cannot be added without becoming reachable.

Hand-written descriptions already in the block are PRESERVED verbatim; only new
files get an auto-description from their first heading. Curate freely — a rerun
keeps what you wrote.

  python3 scripts/refindex.py [--check]

--check exits 1 if any block is out of date (for sync-skills.sh / CI).
"""
import pathlib, re, sys

HEAD = '## Reference files'
CHECK = '--check' in sys.argv
root = pathlib.Path(__file__).resolve().parent.parent


def describe(p):
    """First heading, minus the filename-ish prefix, as a fallback description."""
    for line in p.read_text(errors='replace').splitlines():
        if line.startswith('#'):
            return line.lstrip('# ').strip()
    return p.stem.replace('-', ' ')


def existing(block):
    """Map basename -> the full hand-written bullet already in the block."""
    out, cur, name = {}, [], None
    for line in block.splitlines():
        m = re.match(r'- `references/([^`]+)`', line)
        if m:
            if name:
                out[name] = '\n'.join(cur).rstrip()
            name, cur = m.group(1), [line]
        elif name and (line.startswith('  ') or line.startswith('\t')):
            cur.append(line)
        elif name and not line.strip():
            out[name] = '\n'.join(cur).rstrip(); name, cur = None, []
    if name:
        out[name] = '\n'.join(cur).rstrip()
    return out


stale = []
for skill in sorted(d for d in root.iterdir() if (d / 'SKILL.md').exists()):
    refs = skill / 'references'
    if not refs.is_dir():
        continue
    files = sorted(p for p in refs.rglob('*.md'))
    if not files:
        continue
    f = skill / 'SKILL.md'
    s = f.read_text()

    m = re.search(r'^## Reference files\n(.*?)(?=^## |\Z)', s, re.S | re.M)
    keep = existing(m.group(1)) if m else {}

    lines = [HEAD, '',
             'Every file in `references/` is listed here. Generated by',
             '`scripts/refindex.py` — descriptions you write by hand are preserved.', '']
    for p in files:
        rel = p.relative_to(refs).as_posix()
        lines.append(keep.get(rel, f'- `references/{rel}` — {describe(p)}.'))
    block = '\n'.join(lines) + '\n\n'

    new = s[:m.start()] + block + s[m.end():] if m else None
    if new is None:
        # insert before the final "## Remember"/"## Related skills", else append
        anchor = re.search(r'^## (?:\d+\.\s*)?(?:Remember|Related skills)\b', s, re.M)
        new = (s[:anchor.start()] + block + s[anchor.start():]) if anchor else s.rstrip() + '\n\n' + block
    if new != s:
        stale.append(skill.name)
        if not CHECK:
            f.write_text(new)

if CHECK:
    if stale:
        print('Reference index out of date in: ' + ', '.join(stale), file=sys.stderr)
        print('Run: python3 scripts/refindex.py', file=sys.stderr)
        sys.exit(1)
    print('    reference index current')
else:
    print(f'Reference index regenerated for: {", ".join(stale) if stale else "(no changes)"}')
